// Generates me.bottdev.cloudnetmcp.BuildConfig with values from this build, so the code
// never hard-codes versions. Re-runs automatically when any value changes.
val generateBuildConfig by tasks.registering {
    val outputDir = layout.buildDirectory.dir("generated/sources/buildConfig/kotlin")
    val values = mapOf(
        "NAME" to rootProject.name,
        "VERSION" to project.version.toString(),
        "MCP_SDK_VERSION" to libs.versions.mcp.get(),
    )
    inputs.properties(values)
    outputs.dir(outputDir)

    doLast {
        val file = outputDir.get().file("me/bottdev/cloudnetmcp/BuildConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            buildString {
                appendLine("// Generated by the generateBuildConfig Gradle task. Do not edit.")
                appendLine("package me.bottdev.cloudnetmcp")
                appendLine()
                appendLine("object BuildConfig {")
                values.forEach { (key, value) -> appendLine("    const val $key = \"$value\"") }
                appendLine("}")
            }
        )
    }
}

kotlin.sourceSets.main {
    kotlin.srcDir(generateBuildConfig)
}

